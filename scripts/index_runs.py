#!/usr/bin/env python3
"""Generate docs/06-experiments/INDEX.md from run manifests (never hand-maintained)."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from _common import ROOT, write_text

HEADER = """<!-- GENERATED by scripts/index_runs.py — do not edit by hand. -->
# Experiment index

| Run ID | Experiment | Status | Decision | Submitted | Created (UTC) |
| :--- | :--- | :--- | :--- | :--- | :--- |
"""


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--runs-dir", default=str(ROOT / "runs"))
    p.add_argument("--out", default=str(ROOT / "docs" / "06-experiments" / "INDEX.md"))
    args = p.parse_args(argv)

    rows = []
    runs = Path(args.runs_dir)
    if runs.exists():
        for manifest_path in sorted(runs.glob("*/00_RUN_MANIFEST.json")):
            try:
                m = json.loads(manifest_path.read_text())
            except (OSError, json.JSONDecodeError):
                continue
            results = m.get("results", {})
            rows.append(
                "| {run_id} | {exp} | {status} | {decision} | {submitted} | {created} |".format(
                    run_id=m.get("run_id", "?"),
                    exp=m.get("experiment_id", "?"),
                    status=m.get("status", "?"),
                    decision=results.get("decision") or "",
                    submitted="yes" if results.get("submitted_lora") else "no",
                    created=m.get("created_at_utc", ""),
                )
            )
    write_text(args.out, HEADER + ("\n".join(rows) + "\n" if rows else "| _(none)_ | | | | | |\n"))
    print(f"wrote {args.out} ({len(rows)} runs)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
